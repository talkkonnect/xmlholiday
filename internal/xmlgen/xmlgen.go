// Package xmlgen renders the consolidated FreeSWITCH holiday-override XML.
//
// Generate is a pure function of (year, break setting, saved variable->date
// sets). It performs no I/O, never contacts FreeSWITCH and never emits
// "=true" actions.
package xmlgen

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
	"time"
	"unicode"
)

// Allowed FreeSWITCH condition break values.
var allowedBreaks = map[string]bool{"never": true, "on-true": true, "on-false": true, "always": true}

// DefaultBreak is the PROVISIONAL prototype choice (see SRS §6 / §11).
const DefaultBreak = "never"

// Entry is one saved, selected holiday date for one variable.
type Entry struct {
	Date  string // ISO YYYY-MM-DD
	Label string // optional human readable label
}

// Input to the generator.
type Input struct {
	Year      int
	Break     string             // empty means DefaultBreak
	Calendars map[string][]Entry // exact variable name -> selected dates
}

// Result of a generation run.
type Result struct {
	XML        []byte
	Filename   string
	Variables  int // distinct variables that contributed at least one action
	Dates      int // distinct dates == number of <condition> blocks
	Actions    int
	Conditions int
}

// Filename returns the download filename for year.
func Filename(year int) string { return fmt.Sprintf("freeswitch_holidays_%d.xml", year) }

// ValidateVariable checks a FreeSWITCH variable name. Case and punctuation are
// preserved by callers; this only rejects names that cannot be emitted safely
// as "<name>=false".
func ValidateVariable(v string) error {
	if v == "" {
		return fmt.Errorf("variable name is empty")
	}
	if strings.TrimSpace(v) != v || len(v) > 255 {
		return fmt.Errorf("variable %q has leading/trailing whitespace or is longer than 255 characters", v)
	}
	for _, r := range v {
		if unicode.IsSpace(r) || unicode.IsControl(r) || r == '=' || r == '/' {
			return fmt.Errorf("variable %q contains an invalid character %q (whitespace, '=', '/' and control characters are not allowed)", v, r)
		}
	}
	return nil
}

// ParseDate validates an ISO date and that it belongs to year.
func ParseDate(s string, year int) (time.Time, error) {
	t, err := time.Parse("2006-01-02", s)
	if err != nil {
		return time.Time{}, fmt.Errorf("invalid date %q: must be a real calendar date in YYYY-MM-DD form", s)
	}
	if year != 0 && t.Year() != year {
		return time.Time{}, fmt.Errorf("date %s is not in year %d", s, year)
	}
	return t, nil
}

// Generate builds the XML document. Output is byte-for-byte deterministic for
// the same input: dates are sorted chronologically, variables lexicographically
// (byte order, case-sensitive), and no timestamps are embedded.
func Generate(in Input) (Result, error) {
	if in.Year < 1900 || in.Year > 9999 {
		return Result{}, fmt.Errorf("invalid year %d", in.Year)
	}
	brk := in.Break
	if brk == "" {
		brk = DefaultBreak
	}
	if !allowedBreaks[brk] {
		return Result{}, fmt.Errorf("invalid break value %q (allowed: never, on-true, on-false, always)", brk)
	}

	type dateInfo struct {
		vars   map[string]bool
		labels map[string]bool
	}
	byDate := map[string]*dateInfo{}
	for v, entries := range in.Calendars {
		if err := ValidateVariable(v); err != nil {
			return Result{}, err
		}
		for _, e := range entries {
			if _, err := ParseDate(e.Date, in.Year); err != nil {
				return Result{}, fmt.Errorf("variable %s: %w", v, err)
			}
			di := byDate[e.Date]
			if di == nil {
				di = &dateInfo{vars: map[string]bool{}, labels: map[string]bool{}}
				byDate[e.Date] = di
			}
			di.vars[v] = true
			if l := normalizeLabel(e.Label); l != "" {
				di.labels[l] = true
			}
		}
	}

	dates := make([]string, 0, len(byDate))
	for d := range byDate {
		dates = append(dates, d)
	}
	sort.Strings(dates) // ISO dates sort chronologically

	res := Result{Filename: Filename(in.Year)}
	usedVars := map[string]bool{}
	var b bytes.Buffer
	b.WriteString("<include>\n")
	fmt.Fprintf(&b, "  <!-- Generated by xmlholiday for %d. Holiday overrides only: sets working-time variables to false. -->\n", in.Year)
	fmt.Fprintf(&b, "  <!-- break=%q is a PROVISIONAL setting; verify against the deployed FreeSWITCH dialplan before production use. -->\n", brk)
	fmt.Fprintf(&b, "  <extension name=\"holidays_%d\" continue=\"true\">\n", in.Year)
	for _, d := range dates {
		di := byDate[d]
		vars := make([]string, 0, len(di.vars))
		for v := range di.vars {
			vars = append(vars, v)
		}
		if len(vars) == 0 {
			continue // never emit empty conditions
		}
		sort.Strings(vars)
		if len(di.labels) == 1 {
			for l := range di.labels {
				fmt.Fprintf(&b, "    <!-- %s -->\n", commentSafe(l))
			}
		}
		t, _ := time.Parse("2006-01-02", d)
		fmt.Fprintf(&b, "    <condition mday=\"%02d\" mon=\"%02d\" year=\"%04d\" break=\"%s\">\n", t.Day(), int(t.Month()), t.Year(), attr(brk))
		for _, v := range vars {
			fmt.Fprintf(&b, "      <action application=\"set\" data=\"%s\" inline=\"true\" />\n", attr(v+"=false"))
			usedVars[v] = true
			res.Actions++
		}
		b.WriteString("    </condition>\n")
		res.Conditions++
	}
	b.WriteString("  </extension>\n")
	b.WriteString("</include>\n")

	res.XML = b.Bytes()
	res.Dates = res.Conditions
	res.Variables = len(usedVars)
	return res, nil
}

func normalizeLabel(s string) string { return strings.Join(strings.Fields(s), " ") }

// attr escapes a string for use inside a double-quoted XML attribute.
func attr(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '&':
			b.WriteString("&amp;")
		case '<':
			b.WriteString("&lt;")
		case '>':
			b.WriteString("&gt;")
		case '"':
			b.WriteString("&quot;")
		case '\'':
			b.WriteString("&apos;")
		case '\t':
			b.WriteString("&#x9;")
		case '\n':
			b.WriteString("&#xA;")
		case '\r':
			b.WriteString("&#xD;")
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// commentSafe makes text legal inside <!-- -->: no "--", no trailing "-",
// no control characters.
func commentSafe(s string) string {
	s = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, s)
	for strings.Contains(s, "--") {
		s = strings.ReplaceAll(s, "--", "-")
	}
	return strings.TrimRight(s, "-")
}
